def shoot(fname, path):
    png = os.path.join(OUT, fname + ".png")
    prof = f"/tmp/cr_{fname}"
    subprocess.run(
        ["timeout", "14", "google-chrome", "--headless=old", "--disable-gpu",
         "--no-sandbox", "--disable-dev-shm-usage", "--no-first-run",
         f"--user-data-dir={prof}", "--hide-scrollbars",
         "--force-device-scale-factor=2", "--virtual-time-budget=1800",
         f"--screenshot={png}", "--window-size=560,2600", path],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    im = Image.open(png).convert("RGB")
    bbox = ImageChops.difference(im, Image.new("RGB", im.size, BG)).getbbox()
    if bbox:
        l, t, r, b = bbox
        pad = 22
        im = im.crop((max(0, l - pad), max(0, t - pad),
                      min(im.size[0], r + pad), min(im.size[1], b + pad)))
    canvas = Image.new("RGB", im.size, BG)
    canvas.paste(im, (0, 0))
    canvas.save(png)
    print("saved", os.path.basename(png), canvas.size)


