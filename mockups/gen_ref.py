def item(cmd, desc, ex=None, note=None, reply=False):
    h = f'<div class="item"><span class="cmd rtlcmd">{html.escape(cmd)}</span>'
    if reply:
        h += ' <span class="reply">↩ روی پیام ریپلای کنید</span>'
    h += f'<div class="desc">{html.escape(desc)}</div>'
    if ex:
        h += f'<div class="ex">مثال: <b>{html.escape(ex)}</b></div>'
    if note:
        h += f'<div class="note">💡 {html.escape(note)}</div>'
    h += '</div>'
    return h


def card(fname, title, sub, items):
    doc = TPL.format(title=html.escape(title), sub=html.escape(sub), items="".join(items))
    p = os.path.join(HTML_DIR, fname + ".html")
    with open(p, "w", encoding="utf-8") as f:
        f.write(doc)
    return fname, p


